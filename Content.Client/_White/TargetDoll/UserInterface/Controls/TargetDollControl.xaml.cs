using System.Numerics;
using Content.Client._White.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._White.TargetDoll.UserInterface.Controls;

[GenerateTypedNameReferences]
public sealed partial class TargetDollControl : WhiteTextureRect
{
    public Texture? TextureHovered;
    public Texture? TextureFocused;

    public TargetDollControl()
    {
        RobustXamlLoader.Load(this);
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        if (TextureHovered != null)
            DrawTexture(handle, TextureHovered);

        if (TextureFocused != null)
            DrawTexture(handle, TextureFocused);
    }

    private void DrawTexture(DrawingHandleScreen handle, Texture texture, Color? color = null)
    {
        var size = new Vector2(texture.Width * Scale.X * UIScale, texture.Height * Scale.Y * UIScale);
        var offset = Vector2.Zero;

        handle.DrawTextureRect(texture, new(Vector2.Zero - offset, size - offset), color);
    }
}
