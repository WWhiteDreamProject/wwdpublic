using Content.Client._White.TargetDoll.UserInterface.Controls;
using Content.Shared._White.Body;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._White.TargetDoll.UserInterface.Widgets;

[GenerateTypedNameReferences]
public sealed partial class TargetDollGui : UIWidget
{
    private readonly Dictionary<BodyProviderType, BodyProviderButton> _buttons;

    public TargetDollGui()
    {
        RobustXamlLoader.Load(this);

        var controller = UserInterfaceManager.GetUIController<TargetDollUIController>();

        _buttons = new();
        foreach (var child in Control.Providers.Children)
        {
            if (child is not BodyProviderButton button)
                continue;

            button.MouseFilter = MouseFilterMode.Stop;
            button.OnPressed += _ => controller.SelectProvider(button.Provider);
            button.OnMouseEntered += _ => Control.TextureHovered = button.TextureHovered;
            button.OnMouseExited += _ => Control.TextureHovered = null;

            _buttons[button.Provider] = button;
        }

        OnTargetDollUpdated(BodyProviderType.Chest);
    }

    public void OnTargetDollUpdated(BodyProviderType provider)
    {
        Control.TextureFocused = _buttons[provider].TextureFocused;
    }
}
