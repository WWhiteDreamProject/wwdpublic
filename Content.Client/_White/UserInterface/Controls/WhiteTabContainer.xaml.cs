using System.Linq;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using static Content.Client.Stylesheets.StyleBase;

namespace Content.Client._White.UserInterface.Controls;

/// <summary>
/// A container control that manages multiple tabs with buttons for switching between them.
/// Each tab contains a separate control that is shown when its corresponding button is pressed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WhiteTabContainer : Container
{
    private readonly ButtonGroup _group = new(false);
    private readonly Dictionary<Control, Button> _buttons = new();

    /// <summary>
    /// Event raised when the active tab changes.
    /// </summary>
    public event Action<int>? OnTabChanged;

    /// <summary>
    /// Gets the index of the currently selected tab.
    /// </summary>
    public int CurrentTab { get; private set; }

    /// <summary>
    /// Initializes a new instance of the <see cref="WhiteTabContainer"/> class.
    /// </summary>
    public WhiteTabContainer()
    {
        RobustXamlLoader.Load(this);
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        if (ChildCount == 1 || CurrentTab >= ChildCount + 1)
            return finalSize;

        var buttonBox = new UIBox2i(0, 0, (int) (finalSize.X * UIScale), (int) (ButtonScrollContainer.DesiredSize.Y * UIScale));
        ButtonScrollContainer.ArrangePixel(buttonBox);

        var control = GetChild(CurrentTab + 1);
        control.Visible = true;

        var contentBox = new UIBox2i(0, (int) ButtonScrollContainer.Size.Y, (int) (finalSize.X * UIScale), (int) (finalSize.Y * UIScale));
        control.ArrangePixel(contentBox);

        return finalSize;
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        if (ChildCount == 0)
            return Vector2.Zero;

        var total = ButtonScrollContainer.DesiredSize with { X = 0 };

        ButtonScrollContainer.Measure(availableSize);
        availableSize.Y -= ButtonScrollContainer.DesiredSize.Y;

        var children = Children.ToArray();
        for (var i = 1; i < children.Length; i++)
        {
            var child = children[i];
            if (!child.Visible)
                continue;

            child.Measure(availableSize);
            total = Vector2.Max(child.DesiredSize, total);
        }

        return total;
    }

    protected override void ChildAdded(Control child)
    {
        base.ChildAdded(child);

        if (ChildCount == 1)
            return;

        child.Visible = ChildCount <= 2;

        var button = new Button
        {
            Group = _group,
            HorizontalExpand = true,
            Text = Loc.GetString("tab-container-not-tab-title-provided"),
            StyleClasses = { ButtonOpenBoth },
        };
        ButtonContainer.AddChild(button);

        var tabId = ChildCount - 2;
        button.OnPressed += _ => SetCurrentTab(tabId);
        _buttons.Add(child, button);
    }

    protected override void ChildRemoved(Control child)
    {
        base.ChildRemoved(child);
        if (ButtonContainer.Disposed)
            return;

        if (!_buttons.TryGetValue(child, out var button))
            return;

        ButtonContainer.RemoveChild(button);
    }

    /// <summary>
    /// Gets the title text of the specified tab.
    /// </summary>
    /// <param name="tabId">The zero-based index of the tab.</param>
    /// <returns>The tab title, or an empty string if the tab is not found or has no title.</returns>
    public string GetTabTitle(int tabId)
    {
        var child = ButtonContainer.GetChild(tabId + 1);
        if (child is not Button button)
            return string.Empty;

        if (string.IsNullOrEmpty(button.Text))
            return string.Empty;

        return button.Text;
    }

    /// <summary>
    /// Remove all the children from this tab.
    /// </summary>
    public new void RemoveAllChildren()
    {
        SetCurrentTab(0);

        var children = Children.ToArray();
        for (var i = 1; i < children.Length; i++)
        {
            var child = children[i];
            if (child.Parent != this)
                continue;

            RemoveChild(child);
        }
    }

    /// <summary>
    /// Sets the currently active tab by its index.
    /// </summary>
    /// <param name="tabId">The zero-based index of the tab to activate.</param>
    public void SetCurrentTab(int tabId)
    {
        if (CurrentTab == tabId)
            return;

        var currentTab = GetChild(CurrentTab + 1);
        currentTab.Visible = false;
        CurrentTab = tabId;

        var tab = GetChild(tabId + 1);
        tab.Visible = true;

        InvalidateMeasure();

        OnTabChanged?.Invoke(tabId);
    }

    /// <summary>
    /// Sets the title text for the specified tab.
    /// </summary>
    /// <param name="tab">The zero-based index of the tab.</param>
    /// <param name="title">The new title text for the tab.</param>
    public void SetTabTitle(int tab, string title)
    {
        var child = ButtonContainer.GetChild(tab);
        if (child is not Button button)
            return;

        button.Text = title;
    }

    /// <summary>
    /// Sets the visibility of the specified tab.
    /// </summary>
    /// <param name="tabId">The zero-based index of the tab.</param>
    /// <param name="visible">True to make the tab visible, false to hide it.</param>
    public void SetTabVisible(int tabId, bool visible)
    {
        var button = ButtonContainer.GetChild(tabId + 1);
        button.Visible = visible;
    }
}
