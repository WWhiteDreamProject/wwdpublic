using Content.Shared._White.Humanoid.Markings.Managers;
using Content.Shared._White.Humanoid.Markings.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._White.Humanoid.Markings.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class CategoryMarkingPicker : Control
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly MarkingManager _marking = default!;

    private readonly MarkingsViewModel _model;
    private readonly ProtoId<MarkingCategoryPrototype> _category;

    public bool Empty => Pickers.ChildCount == 0;

    public CategoryMarkingPicker(MarkingsViewModel model, ProtoId<MarkingCategoryPrototype> category)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _model = model;
        _category = category;

        UpdateMarkings();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _model.EnforcementsChanged += UpdateMarkings;
        _model.SexChanged += UpdateMarkings;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _model.EnforcementsChanged -= UpdateMarkings;
        _model.SexChanged -= UpdateMarkings;
    }

    private void UpdateMarkings()
    {
        Pickers.RemoveAllChildren();

        if (!_marking.TryGetMarkings(_category, out var markings))
            return;

        var available = new HashSet<MarkingPrototype>();
        foreach (var layer in _marking.GetLayers(_category))
        {
            if (!_model.AppearanceData.TryGetValue(layer, out var appearanceData))
                continue;

            if (!_model.MarkingsData.TryGetValue(layer, out var markingData))
                continue;

            if (!_prototype.TryIndex(markingData.Group, out var group))
                continue;

            if (!group.Data.ContainsKey(_category))
                continue;

            if (!_model.EnforceGroupAndSexRestrictions)
                continue;

            var whitelisted = _marking.Whitelisted(_category, group);
            foreach (var marking in markings)
            {
                if (!_marking.CanBeApplied(marking, whitelisted, group, appearanceData.Sex))
                    continue;

                available.Add(marking);
            }
        }

        if (available.Count == 0)
            return;

        var control = new SingleMarkingPicker(available, _model, _category);
        Pickers.AddChild(control);
    }
}
