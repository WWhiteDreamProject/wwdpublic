using Content.Shared._White.Colors.Strategies;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._White.Colors.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class ColorPicker : BoxContainer
{
    /// <summary>
    /// Current selected color.
    /// </summary>
    public Color Color {get; private set;}

    /// <summary>
    /// Current coloration strategy used for color selection.
    /// </summary>
    public IColorationStrategy Strategy { get; private set; } = new SimpleColoration();

    /// <summary>
    /// Event raised when the color is changed.
    /// </summary>
    public event Action<Color>? OnColorChanged;

    /// <summary>
    /// Text displayed in the color picker label.
    /// </summary>
    public string? Text
    {
        get => Label.Text;
        set => Label.Text = value;
    }

    public ColorPicker()
    {
        RobustXamlLoader.Load(this);

        Selector.OnColorChanged += _ => { OnSelectorChanged(); };
        Slider.OnValueChanged += _ => { OnSliderChanged(); };
    }

    private void OnSelectorChanged()
    {
        if (!Selector.Visible)
            return;

        var color = Strategy.EnsureVerified(Selector.Color);
        SetColor(color);
    }

    private void OnSliderChanged()
    {
        if (!Slider.Visible)
            return;

        var color = Strategy.FromUnary(Slider.Value);
        SetColor(color);
    }

    /// <summary>
    /// Sets the current color and invokes the color changed event.
    /// </summary>
    /// <param name="color">The color to set.</param>
    public void SetColor(Color color)
    {
        if (color == Color)
            return;

        Color = color;
        OnColorChanged?.Invoke(Color);
    }

    /// <summary>
    /// Sets the coloration strategy and updates the UI accordingly.
    /// </summary>
    /// <param name="strategy">The coloration strategy to use.</param>
    public void SetStrategy(IColorationStrategy strategy)
    {
        if (Strategy == strategy)
            return;

        Strategy = strategy;

        switch (Strategy.InputType)
        {
            case ColorationStrategyInput.Unary:
            {
                Slider.Visible = true;
                Selector.Visible = false;

                OnSliderChanged();

                break;
            }
            case ColorationStrategyInput.Color:
            default:
            {
                Slider.Visible = false;
                Selector.Visible = true;

                OnSelectorChanged();

                break;
            }
        }

        Update();
    }

    /// <summary>
    /// Updates the UI controls to reflect the current color and strategy.
    /// </summary>
    public void Update()
    {
        if (Selector.Visible)
            Selector.Color = Strategy.EnsureVerified(Color);

        if (!Slider.Visible)
            return;

        Slider.Value = Strategy.ToUnary(Color);
    }
}

